class AuthManager {
    constructor() {
        this.currentLang = localStorage.getItem('language') || 'ru';
        this.generateAttempts = 5;
        this.manualUsernameAllowed = false;
        this.commonPasswords = [
            'password', '123456', '12345678', '123456789', '12345',
            'qwerty', 'abc123', 'password1', '1234567', '1234567890',
            'iloveyou', 'admin', 'welcome', 'monkey', '123123',
            'sunshine', 'letmein', '1234', 'password123', 'shadow'
        ];
        
        this.init();
    }

    init() {
        if (!document.getElementById('login-form') && !document.getElementById('register-form')) {
            return;
        }

        this.setupEventListeners();
        this.applytranslati();
        this.setupLanguageObserver();
        this.generateUsername();
    }

    setupEventListeners() {
        const authTabs = document.querySelectorAll('.auth-tab');
        const passwordTypeRadios = document.querySelectorAll('input[name="password-type"]');
        const generateUsernameBtn = document.getElementById('generate-username');
        const registerForm = document.getElementById('register-form');
        const loginForm = document.getElementById('login-form');
        const phoneInput = document.getElementById('phone');

        authTabs.forEach(tab => {
            tab.addEventListener('click', () => {
                const tabName = tab.getAttribute('data-tab');
                this.switchTab(tabName);
            });
        });

        passwordTypeRadios.forEach(radio => {
            radio.addEventListener('change', () => {
                this.togglePasswordFields();
            });
        });

        if (generateUsernameBtn) {
            generateUsernameBtn.addEventListener('click', () => this.generateUsername());
        }

        if (registerForm) {
            registerForm.addEventListener('input', (e) => {
                this.validateField(e.target);
                this.validateRegisterForm();
            });
        }

        if (loginForm) {
            loginForm.addEventListener('submit', (e) => this.handleLogin(e));
        }
        
        if (registerForm) {
            registerForm.addEventListener('submit', (e) => this.handleRegistration(e));
        }

        if (phoneInput) {
            phoneInput.addEventListener('input', (e) => this.formatPhoneNumber(e));
        }
    }

    applytranslati() {
        const t = translati[this.currentLang];
        if (!t) return;

        const elements = document.querySelectorAll('[data-i18n]');
        elements.forEach(element => {
            const key = element.getAttribute('data-i18n');
            if (t[key]) {
                element.textContent = t[key];
            }
        });

        const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
        placeholders.forEach(element => {
            const key = element.getAttribute('data-i18n-placeholder');
            if (t[key]) {
                element.placeholder = t[key];
            }
        });

        const labels = document.querySelectorAll('label[data-i18n]');
        labels.forEach(label => {
            const key = label.getAttribute('data-i18n');
            if (t[key]) {
                label.textContent = t[key];
            }
        });

        const buttons = document.querySelectorAll('button[data-i18n]');
        buttons.forEach(button => {
            const key = button.getAttribute('data-i18n');
            if (t[key]) {
                button.textContent = t[key];
            }
        });
    }

    setupLanguageObserver() {
        document.addEventListener('languageChanged', () => {
            this.currentLang = localStorage.getItem('language') || 'ru';
            this.applytranslati();
        });
    }

    switchTab(tabName) {
        const authTabs = document.querySelectorAll('.auth-tab');
        const authForms = document.querySelectorAll('.auth-form');
        
        authTabs.forEach(t => t.classList.remove('active'));
        authForms.forEach(form => form.classList.remove('active'));
        
        document.querySelector(`.auth-tab[data-tab="${tabName}"]`).classList.add('active');
        document.getElementById(`${tabName}-form`).classList.add('active');
    }

    togglePasswordFields() {
        const passwordType = document.querySelector('input[name="password-type"]:checked');
        const manualPasswordFields = document.querySelectorAll('.manual-password');
        const passwordInput = document.getElementById('password');
        const confirmPasswordInput = document.getElementById('confirm-password');
        
        manualPasswordFields.forEach(field => {
            field.classList.toggle('hidden', passwordType.value !== 'manual');
        });
        
        if (passwordType.value === 'manual') {
            if (passwordInput) passwordInput.setAttribute('required', 'true');
            if (confirmPasswordInput) confirmPasswordInput.setAttribute('required', 'true');
        } else {
            if (passwordInput) passwordInput.removeAttribute('required');
            if (confirmPasswordInput) confirmPasswordInput.removeAttribute('required');
        }
        
        this.validateRegisterForm();
    }

    validateField(field) {
        if (!field || !field.parentElement) return false;
        
        const errorElement = field.parentElement.querySelector('.error-message');
        if (errorElement) {
            errorElement.textContent = '';
        }
        field.classList.remove('error');
        
        const t = translati[this.currentLang];
        
        switch(field.name) {
            case 'phone':
                return this.validatePhone(field, errorElement, t);
            case 'email':
                return this.validateEmail(field, errorElement, t);
            case 'birthdate':
                return this.validateBirthdate(field, errorElement, t);
            case 'password':
                return this.validatePassword(field, errorElement, t);
            case 'confirm-password':
                return this.validateConfirmPassword(field, errorElement, t);
            case 'lastname':
            case 'firstname':
            case 'middlename':
                return this.validateName(field, errorElement, t);
            case 'username':
                return this.validateUsername(field, errorElement, t);
            default:
                return true;
        }
    }

    validatePhone(field, errorElement, t) {
        const phone = field.value.trim();
        const belarusRegex = /^(\+375|80)(29|25|44|33)(\d{3})(\d{2})(\d{2})$/;
        
        if (!phone) {
            if (errorElement) errorElement.textContent = t['validation.required'];
            field.classList.add('error');
            return false;
        }
        
        const cleanPhone = phone.replace(/[^\d+]/g, '');
        
        if (!belarusRegex.test(cleanPhone)) {
            if (errorElement) errorElement.textContent = t['validation.phone'];
            field.classList.add('error');
            return false;
        }
        
        return true;
    }

    validateEmail(field, errorElement, t) {
        const email = field.value.trim();
        const emailRegex = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;
        
        if (!email) {
            if (errorElement) errorElement.textContent = t['validation.required'];
            field.classList.add('error');
            return false;
        }
        
        if (!emailRegex.test(email)) {
            if (errorElement) errorElement.textContent = t['validation.email'];
            field.classList.add('error');
            return false;
        }
        
        return true;
    }

    validateBirthdate(field, errorElement, t) {
        const birthdate = new Date(field.value);
        const today = new Date();
        const minAgeDate = new Date();
        minAgeDate.setFullYear(today.getFullYear() - 16);
        
        if (!field.value) {
            if (errorElement) errorElement.textContent = t['validation.required'];
            field.classList.add('error');
            return false;
        }
        
        if (birthdate > minAgeDate) {
            if (errorElement) errorElement.textContent = t['validation.birthdate'];
            field.classList.add('error');
            return false;
        }
        
        return true;
    }

    validatePassword(field, errorElement, t) {
        const password = field.value;
        
        if (!password) {
            if (errorElement) errorElement.textContent = t['validation.required'];
            field.classList.add('error');
            return false;
        }
        
        if (password.length < 8 || password.length > 20) {
            if (errorElement) errorElement.textContent = t['validation.password.length'];
            field.classList.add('error');
            return false;
        }
        
        if (!/(?=.*[a-z])/.test(password)) {
            if (errorElement) errorElement.textContent = t['validation.password.lowercase'];
            field.classList.add('error');
            return false;
        }
        
        if (!/(?=.*[A-Z])/.test(password)) {
            if (errorElement) errorElement.textContent = t['validation.password.uppercase'];
            field.classList.add('error');
            return false;
        }
        
        if (!/(?=.*\d)/.test(password)) {
            if (errorElement) errorElement.textContent = t['validation.password.number'];
            field.classList.add('error');
            return false;
        }
        
        if (!/(?=.*[!@#$%^&*()_+\-=\[\]{};':"\\|,.<>\/?])/.test(password)) {
            if (errorElement) errorElement.textContent = t['validation.password.special'];
            field.classList.add('error');
            return false;
        }
        
        if (this.commonPasswords.includes(password.toLowerCase())) {
            if (errorElement) errorElement.textContent = t['validation.password.common'];
            field.classList.add('error');
            return false;
        }
        
        return true;
    }

    validateConfirmPassword(field, errorElement, t) {
        const password = document.getElementById('password')?.value || '';
        const confirmPassword = field.value;
        
        if (!confirmPassword) {
            if (errorElement) errorElement.textContent = t['validation.required'];
            field.classList.add('error');
            return false;
        }
        
        if (password !== confirmPassword) {
            if (errorElement) errorElement.textContent = t['validation.password.match'];
            field.classList.add('error');
            return false;
        }
        
        return true;
    }

    validateName(field, errorElement, t) {
        const name = field.value.trim();
        
        if (field.required && !name) {
            if (errorElement) errorElement.textContent = t['validation.required'];
            field.classList.add('error');
            return false;
        }
        
        if (name && !/^[a-zA-Zа-яА-ЯёЁ\s\-]+$/.test(name)) {
            if (errorElement) errorElement.textContent = t['validation.name.format'];
            field.classList.add('error');
            return false;
        }
        
        return true;
    }

    validateUsername(field, errorElement, t) {
        const username = field.value.trim();
        
        if (!username) {
            if (errorElement) errorElement.textContent = t['validation.required'];
            field.classList.add('error');
            return false;
        }
        
        if (username.length < 3) {
            if (errorElement) errorElement.textContent = t['validation.username.length'];
            field.classList.add('error');
            return false;
        }
        
        if (!/^[a-zA-Z0-9_\-]+$/.test(username)) {
            if (errorElement) errorElement.textContent = t['validation.username.format'];
            field.classList.add('error');
            return false;
        }
        
        return true;
    }

    generateUsername() {
        const usernameInput = document.getElementById('username');
        const generateUsernameBtn = document.getElementById('generate-username');
        const generateAttemptsSpan = document.getElementById('generate-attempts');
        const usernameInfo = document.querySelector('.username-info');
        const t = translati[this.currentLang];
        
        if (!usernameInput || !generateAttemptsSpan) return;
        
        if (this.generateAttempts <= 0 && !this.manualUsernameAllowed) {
            this.manualUsernameAllowed = true;
            usernameInput.removeAttribute('readonly');
            if (generateUsernameBtn) generateUsernameBtn.style.display = 'none';
            if (usernameInfo && t['auth.register.username.manual']) {
                usernameInfo.textContent = t['auth.register.username.manual'];
            }
            return;
        }
        
        if (this.generateAttempts > 0) {
            this.generateAttempts--;
            if (generateAttemptsSpan && t['auth.register.username.attempts']) {
                generateAttemptsSpan.textContent = t['auth.register.username.attempts'] + ' ' + this.generateAttempts;
            }
        }
        
        const adjectives = ['Cool', 'Smart', 'Fast', 'Brave', 'Happy', 'Clever', 'Wise', 'Young', 'Great', 'Super'];
        const nouns = ['Tiger', 'Eagle', 'Lion', 'Wolf', 'Bear', 'Fox', 'Hawk', 'Shark', 'Dragon', 'Phoenix'];
        const numbers = Math.floor(Math.random() * 1000);
        
        const randomAdjective = adjectives[Math.floor(Math.random() * adjectives.length)];
        const randomNoun = nouns[Math.floor(Math.random() * nouns.length)];
        
        const username = `${randomAdjective}${randomNoun}${numbers}`.toLowerCase();
        usernameInput.value = username;
        
        if (this.generateAttempts === 0 && generateUsernameBtn && t['auth.register.username.generate']) {
            generateUsernameBtn.textContent = t['auth.register.username.generate'];
        }
        
        this.validateField(usernameInput);
        this.validateRegisterForm();
    }

    validateRegisterForm() {
        const registerForm = document.getElementById('register-form');
        const registerBtn = document.getElementById('register-btn');
        const agreementCheckbox = document.getElementById('agreement');
        const t = translati[this.currentLang];
        
        if (!registerForm) return false;
        
        const fields = registerForm.querySelectorAll('input[required]');
        let isValid = true;
        
        fields.forEach(field => {
            if (!this.validateField(field)) isValid = false;
        });
        
        if (agreementCheckbox && !agreementCheckbox.checked) isValid = false;
        
        const passwordType = document.querySelector('input[name="password-type"]:checked');
        if (passwordType && passwordType.value === 'manual') {
            const password = document.getElementById('password');
            const confirmPassword = document.getElementById('confirm-password');
            
            if (password && !this.validateField(password)) isValid = false;
            if (confirmPassword && !this.validateField(confirmPassword)) isValid = false;
        }
        
        if (registerBtn) registerBtn.disabled = !isValid;
        return isValid;
    }

    async handleLogin(e) {
        e.preventDefault();
        const loginForm = document.getElementById('login-form');
        const t = translati[this.currentLang];
        
        if (!loginForm) return;
        
        const formData = {
            email: document.getElementById('login-email')?.value || '',
            password: document.getElementById('login-password')?.value || ''
        };
        
        try {
            const response = await fetch('http://localhost:3000/users');
            const users = await response.json();
            
            const user = users.find(u => 
                (u.email === formData.email || u.phone === formData.email) && 
                u.password === formData.password
            );
            
            if (user) {
                alert(t['message.login.success']);
                localStorage.setItem('currentUser', JSON.stringify(user));
                window.location.href = 'home.html';
            } else {
                alert(t['message.login.error']);
            }
        } catch (error) {
            console.error('Login error:', error);
            alert(t['message.login.failed']);
        }
    }

    async handleRegistration(e) {
        e.preventDefault();
        const registerForm = document.getElementById('register-form');
        const agreementCheckbox = document.getElementById('agreement');
        const t = translati[this.currentLang];
        
        if (!registerForm || !this.validateRegisterForm()) return;
        
        if (!agreementCheckbox.checked) {
            alert(t['message.agreement.required']);
            return;
        }
        
        const passwordType = document.querySelector('input[name="password-type"]:checked');
        let password;
        
        if (passwordType && passwordType.value === 'manual') {
            password = document.getElementById('password')?.value || '';
        } else {
            password = this.generateRandomPassword();
            alert(t['message.password.generated'].replace('{password}', password));
        }
        
        const userData = {
            phone: document.getElementById('phone')?.value.replace(/[^\d+]/g, '') || '',
            email: document.getElementById('email')?.value || '',
            birthdate: document.getElementById('birthdate')?.value || '',
            lastname: document.getElementById('lastname')?.value || '',
            firstname: document.getElementById('firstname')?.value || '',
            middlename: document.getElementById('middlename')?.value || '',
            username: document.getElementById('username')?.value || '',
            password: password,
            role: 'user',
            registrationDate: new Date().toISOString()
        };
        
        try {
            const checkResponse = await fetch('http://localhost:3000/users');
            const users = await checkResponse.json();
            
            const existingUser = users.find(u => 
                u.email === userData.email || u.phone === userData.phone || u.username === userData.username
            );
            
            if (existingUser) {
                if (existingUser.email === userData.email) alert(t['message.user.exists.email']);
                else if (existingUser.phone === userData.phone) alert(t['message.user.exists.phone']);
                else alert(t['message.user.exists.username']);
                return;
            }
            
            const response = await fetch('http://localhost:3000/users', {
                method: 'POST',
                headers: {'Content-Type': 'application/json'},
                body: JSON.stringify(userData)
            });
            
            if (response.ok) {
                const newUser = await response.json();
                alert(t['message.register.success']);
                localStorage.setItem('currentUser', JSON.stringify(newUser));
                window.location.href = 'home.html';
            } else throw new Error('Registration failed');
        } catch (error) {
            console.error('Registration error:', error);
            alert(t['message.register.error']);
        }
    }

    generateRandomPassword() {
        const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789!@#$%^&*()_+-=';
        let password = 'Aal!';
        
        for (let i = 4; i < 12; i++) {
            password += chars.charAt(Math.floor(Math.random() * chars.length));
        }
        
        return password.split('').sort(() => 0.5 - Math.random()).join('');
    }

    formatPhoneNumber(e) {
        let value = e.target.value.replace(/\D/g, '');
        
        if (value.startsWith('375')) value = '+' + value;
        else if (value.startsWith('80')) value = '+375' + value.substring(2);
        
        if (value.length > 3) value = value.substring(0, 4) + ' ' + value.substring(4);
        if (value.length > 6) value = value.substring(0, 6) + ' ' + value.substring(6);
        if (value.length > 9) value = value.substring(0, 9) + ' ' + value.substring(9);
        if (value.length > 12) value = value.substring(0, 12) + ' ' + value.substring(12);
        
        e.target.value = value;
    }
}

document.addEventListener('DOMContentLoaded', () => {
    const authManager = new AuthManager();
    window.authManager = authManager;
});